describe("extractCoreMarkedEntries", () => {
  test("SC-001: an entry followed by ***CORE*** is included", () => {
    const source = "# Judgments\n\n### [judgment] Kept\n\n***CORE***\n\nBody one.\n\n### [judgment] Also kept\n\n***CORE***\n\nBody two.\n";
    const result = extractCoreMarkedEntries(source);
    expect(result).toEqual([
      "### [judgment] Kept\n\nBody one.",
      "### [judgment] Also kept\n\nBody two.",
    ]);
  });

  test("SC-002: an entry with no marker is excluded", () => {
    const source = "### [judgment] Kept\n\n***CORE***\n\nBody one.\n\n### [decision] Dropped\n\nBody two, no marker.\n";
    const result = extractCoreMarkedEntries(source);
    expect(result).toEqual(["### [judgment] Kept\n\nBody one."]);
  });

  test("tolerates blank lines between header and marker", () => {
    const source = "### [judgment] Kept\n\n\n***CORE***\n\nBody.\n";
    expect(extractCoreMarkedEntries(source)).toEqual(["### [judgment] Kept\n\nBody."]);
  });
});

describe("extractAllowlistedEntries", () => {
  const TITLES = ["Kept one", "Kept two"];

  test("SC-003: allowlisted titles are included in file order", () => {
    const source = "### [preference] Kept one\n\nBody one.\n\n### [preference] Not listed\n\nBody two.\n\n### [preference] Kept two\n\nBody three.\n";
    expect(extractAllowlistedEntries(source, TITLES)).toEqual([
      "### [preference] Kept one\n\nBody one.",
      "### [preference] Kept two\n\nBody three.",
    ]);
  });

  test("SC-004: a non-allowlisted title is excluded even when required titles are present", () => {
    const source = "### [preference] Not listed\n\nBody.\n\n### [preference] Kept one\n\nBody one.\n\n### [preference] Kept two\n\nBody three.\n";
    expect(extractAllowlistedEntries(source, TITLES)).toEqual([
      "### [preference] Kept one\n\nBody one.",
      "### [preference] Kept two\n\nBody three.",
    ]);
  });

  test("SC-005: a missing required title throws naming it", () => {
    const source = "### [preference] Kept one\n\nBody one.\n";
    expect(() => extractAllowlistedEntries(source, TITLES)).toThrow("Kept two");
  });
});

