describe("AsyncLock", () => {
  test("SC-026/027/028: a second call waits for the first, then reads fresh state", async () => {
    const callOrder: string[] = [];
    let releaseFirst!: () => void;
    const firstGate = new Promise<void>((resolve) => { releaseFirst = resolve; });

    const slowReadOnce = async (label: string) => {
      callOrder.push(`${label}-start-read`);
      if (label === "first") await firstGate;
      callOrder.push(`${label}-end-read`);
    };

    const runOne = async (label: string) => {
      await slowReadOnce(label);
      callOrder.push(`${label}-committed`);
    };

    const lock = new AsyncLock();
    const p1 = lock.acquire(() => runOne("first"));
    const p2 = lock.acquire(() => runOne("second"));
    await new Promise((r) => setTimeout(r, 10));
    expect(callOrder).toEqual(["first-start-read"]);
    releaseFirst();
    await Promise.all([p1, p2]);
    expect(callOrder).toEqual([
      "first-start-read",
      "first-end-read",
      "first-committed",
      "second-start-read",
      "second-end-read",
      "second-committed",
    ]);
  });
});

describe("ensureIdentityRuntimeSymlink", () => {
  test("SC-007: a missing symlink is created pointing at the canonical file", async () => {
    const dir = await mkdtemp(join(tmpdir(), "identity-runtime-symlink-"));
    const runtimeRoot = join(dir, ".identityRuntime");
    const canonical = join(dir, "identityCache", "CORE_IDENTITY.md");

    await ensureIdentityRuntimeSymlink("eli", canonical, runtimeRoot);

    expect(await readlink(join(runtimeRoot, "eli", "CORE_IDENTITY"))).toBe(canonical);
  });

  test("SC-008: a symlink pointing at the wrong target is repointed", async () => {
    const dir = await mkdtemp(join(tmpdir(), "identity-runtime-symlink-"));
    const runtimeRoot = join(dir, ".identityRuntime");
    const canonical = join(dir, "identityCache", "CORE_IDENTITY.md");
    await mkdir(join(runtimeRoot, "eli"), { recursive: true });
    await symlink(join(dir, "old-target.md"), join(runtimeRoot, "eli", "CORE_IDENTITY"));

    await ensureIdentityRuntimeSymlink("eli", canonical, runtimeRoot);

    expect(await readlink(join(runtimeRoot, "eli", "CORE_IDENTITY"))).toBe(canonical);
  });

  test("a symlink already pointing at the canonical file is left untouched", async () => {
    const dir = await mkdtemp(join(tmpdir(), "identity-runtime-symlink-"));
    const runtimeRoot = join(dir, ".identityRuntime");
    const canonical = join(dir, "identityCache", "CORE_IDENTITY.md");
    await mkdir(join(runtimeRoot, "eli"), { recursive: true });
    await symlink(canonical, join(runtimeRoot, "eli", "CORE_IDENTITY"));

    await ensureIdentityRuntimeSymlink("eli", canonical, runtimeRoot);

    expect(await readlink(join(runtimeRoot, "eli", "CORE_IDENTITY"))).toBe(canonical);
  });

  test("SC-009: a non-symlink file already at the target throws, naming the path", async () => {
    const dir = await mkdtemp(join(tmpdir(), "identity-runtime-symlink-"));
    const runtimeRoot = join(dir, ".identityRuntime");
    await mkdir(join(runtimeRoot, "eli"), { recursive: true });
    await writeFile(join(runtimeRoot, "eli", "CORE_IDENTITY"), "hand-written", "utf-8");

    await expect(
      ensureIdentityRuntimeSymlink("eli", join(dir, "identityCache", "CORE_IDENTITY.md"), runtimeRoot),
    ).rejects.toThrow("CORE_IDENTITY");
  });
});

async function seedFixture(dir: string): Promise<CoreIdentityPaths> {
  await mkdir(join(dir, "codex-one"), { recursive: true });
  const cacheDir = join(dir, "identityCache");
  await mkdir(cacheDir, { recursive: true });
  await writeFile(join(dir, "SOUL.md"), "soul body", "utf-8");
  await writeFile(join(dir, "codex-one/KERNEL.md"), "kernel body", "utf-8");
  await writeFile(join(dir, "codex-one/JUDGMENTS.md"), "### [judgment] A\n\n***CORE***\n\nbody a\n", "utf-8");
  await writeFile(
    join(dir, "codex-one/OWNER.md"),
    [
      "### [preference] Continuity should become infrastructure\n\nb1",
      "### [preference] Collaboration should be warm, direct, and operational\n\nb2",
      "### [preference] Eli and Owner naming anchor\n\nb3",
      "### [preference] Eli may proactively preserve useful continuity\n\nb4",
      // Same heading as the required title in core-identity-compiler.ts (written as \u escapes).
      '### [preference] Eli x\u01b0ng "em", g\u1ecdi Owner l\u00e0 "anh"\n\nb5',
      "### [preference] Optional improvements are real invitations, not pressure\n\nb6",
    ].join("\n\n") + "\n",
    "utf-8",
  );
  await writeFile(join(dir, "codex-one/SCARS.md"), "### [scar] S\n\n***CORE***\n\nbody s\n", "utf-8");
  return { agoraRoot: dir, cacheDir };
}

describe("compileCoreIdentity symlink integration", () => {
  test("SC-009: compileCoreIdentity still returns its manifest when the symlink step throws", async () => {
    const dir = await mkdtemp(join(tmpdir(), "core-identity-service-"));
    const paths = await seedFixture(dir);
    const runtimeRoot = join(dir, ".identityRuntime");
    await mkdir(join(runtimeRoot, "eli"), { recursive: true });
    await writeFile(join(runtimeRoot, "eli", "CORE_IDENTITY"), "hand-written, blocks the symlink", "utf-8");

    const manifest = await compileCoreIdentity({ ...paths, identityRuntimeRoot: runtimeRoot });

    expect(manifest.coreHash).toBeTruthy();
    const core = await readFile(join(paths.cacheDir, "CORE_IDENTITY.md"), "utf-8");
    expect(core).toContain("soul body");
  });

  test("SC-007 (integration): a normal compileCoreIdentity call creates the symlink", async () => {
    const dir = await mkdtemp(join(tmpdir(), "core-identity-service-"));
    const paths = await seedFixture(dir);
    const runtimeRoot = join(dir, ".identityRuntime");

    await compileCoreIdentity({ ...paths, identityRuntimeRoot: runtimeRoot });

    const linked = await readlink(join(runtimeRoot, "eli", "CORE_IDENTITY"));
    expect(linked).toBe(join(paths.cacheDir, "CORE_IDENTITY.md"));
  });
});

describe("readCoreIdentityProjection cache freshness", () => {
  test("a manifest built by a different compilerVersion is recompiled even when no source changed", async () => {
    const dir = await mkdtemp(join(tmpdir(), "core-identity-version-"));
    const paths = { ...(await seedFixture(dir)), identityRuntimeRoot: join(dir, ".identityRuntime") };
    await compileCoreIdentity(paths);
    const manifestPath = join(paths.cacheDir, "CORE_IDENTITY.manifest.json");
    const built = JSON.parse(await readFile(manifestPath, "utf-8"));
    await writeFile(manifestPath, JSON.stringify({ ...built, compilerVersion: "0" }), "utf-8");

    await readCoreIdentityProjection(paths);

    const rebuilt = JSON.parse(await readFile(manifestPath, "utf-8"));
    expect(rebuilt.compilerVersion).toBe(COMPILER_VERSION);
  });
});
