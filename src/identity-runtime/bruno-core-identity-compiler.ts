import { homedir } from "node:os";
import { join as joinPath, dirname } from "node:path";
import { load as loadYaml } from "js-yaml";
import { MappedFilesystemAdapter } from "../substrate/mapped-filesystem-adapter";
import { sha256Hex, writeFileAtomic, AsyncLock } from "./core-identity-compiler";
import { HeadingLeadParagraphDistiller, type DistillAdapter } from "./bruno-distill";
import { DEFAULT_WRITE_SCOPES } from "../memory/scoped-store";
import type { RuntimeProjection } from "./contract/runtime-projection.ts";

/**
 * Bruno's CORE_IDENTITY compiler — the SOUL + IDENTITY_IMMEDIATE pattern
 * (mirrors eli's core-identity-compiler.ts, per the archived
 * 2026-07-30-core-identity-immediate-compiler change): a static curated
 * core (axioms + distilled self + distilled owner) plus an "immediate"
 * layer resolved from the `current_state` scope of the real
 * substrate.map.yaml (state/ + CURRENT.md) — the always-changing part.
 *
 * Lives inside ANIMA (src/identity-runtime/), not inside bruno-runtime:
 * per the archived 2026-07-30-identity-runtime-web-service design,
 * Decision 1 (Approved Option B), canonical compilation is ANIMA's job —
 * the runtime process must never compile its own projection ("Sharing
 * ANIMA's raw store with <identity>-runtime is forbidden").
 *
 * Files are resolved via MappedFilesystemAdapter + the real
 * substrate.map.yaml (System B), never a hardcoded path list. The
 * identity_core scope resolves to whole 0_SOUL/ + 1_EGO/ directories;
 * the compiler curates that down to axioms.md + self.md (and owner.md
 * from the relationship scope) so the output stays well under
 * raw-dumping every resolved file. current_state files, when present,
 * are included verbatim (evidence_required: false in the real map —
 * their absence must still compile, and does, with the immediate block
 * omitted).
 */

export interface BrunoCoreIdentityPaths {
  /** ~/substrate in production; a fixture root in tests. */
  substrateRoot: string;
  /** Test-only override; defaults to ~/.identityRuntime. */
  identityRuntimeRoot?: string;
  /** Defaults to HeadingLeadParagraphDistiller; inject an LLMDistiller once one is wired. */
  distiller?: DistillAdapter;
}

const SEP = "\n\n---\n\n";
// "2": the owner.md section label changed (private section), so cached output is rebuilt.
export const BRUNO_COMPILER_VERSION = "2";

export interface BrunoCoreIdentityManifest {
  sourceHashes: { axioms: string; self: string; owner: string; currentState: string };
  immediateHash: string;
  coreHash: string;
  builtAt: string;
  compilerVersion: string;
}

const RECALL_SECTION = `## Tools — recall is real infrastructure, not a habit to remember

\`recall\` already performs federated dispatch automatically:
- Colony/agent-information queries → \`hive search\` (\`~/agora/hive/bin/hive\`).
- Queries about Bruno's own history → \`BrunoEntityAdapter\` (backed by
  \`~/work/bruno-entity/scripts/recall.mjs\`).

When \`~/work/bruno-entity/scripts/recall.mjs\`'s heartbeat environment isn't
running (a plain Claude Code session, for example), call the same capability
over HTTP: \`POST /v1/continuity/recall\` on \`bruno-runtime\`.
`;

const IMMEDIATE_HEADER =
  "# Identity Core — Immediate (current_state)\n\n" +
  "This file is generated by bruno's core-identity compiler from the\n" +
  "`current_state` scope of substrate.map.yaml (state/ and CURRENT.md).\n" +
  "Do not hand-edit; edit the sources and let the compiler resynthesize.";

const EMPTY_IMMEDIATE =
  "# Identity Core — Immediate (current_state)\n\n" +
  "This file is generated by bruno's core-identity compiler from the\n" +
  "`current_state` scope of substrate.map.yaml (state/ and CURRENT.md).\n" +
  "No current_state sources resolved (the declared paths do not exist\n" +
  "yet) — the immediate layer is empty. Do not hand-edit; edit the\n" +
  "sources and let the compiler resynthesize.";

function defaultIdentityRuntimeRoot(): string {
  return joinPath(homedir(), ".identityRuntime");
}

function outputPath(identityRuntimeRoot: string): string {
  return joinPath(identityRuntimeRoot, "bruno", "CORE_IDENTITY.md");
}

function immediateOutputPath(identityRuntimeRoot: string): string {
  return joinPath(identityRuntimeRoot, "bruno", "IDENTITY_CORE_IMMEDIATE.md");
}

function manifestPath(identityRuntimeRoot: string): string {
  return joinPath(identityRuntimeRoot, "bruno", "CORE_IDENTITY.manifest.json");
}

async function readManifest(identityRuntimeRoot: string): Promise<BrunoCoreIdentityManifest | null> {
  const file = Bun.file(manifestPath(identityRuntimeRoot));
  if (!(await file.exists())) return null;
  try {
    return JSON.parse(await file.text()) as BrunoCoreIdentityManifest;
  } catch {
    return null;
  }
}

function adapterFor(substrateRoot: string, rawMap: string): MappedFilesystemAdapter {
  const mapContent = JSON.stringify(loadYaml(rawMap));
  return new MappedFilesystemAdapter(mapContent, { mapPath: joinPath(substrateRoot, "substrate.map.yaml"), rootOverride: substrateRoot });
}

/** Resolves identity_core + relationship via the real substrate map, filtered to the curated file set. */
async function resolveCuratedSources(substrateRoot: string): Promise<{ axioms: string; self: string; owner: string }> {
  const adapter = adapterFor(substrateRoot, await Bun.file(joinPath(substrateRoot, "substrate.map.yaml")).text());

  const identityCore = await adapter.retrieve({ scopes: ["identity_core"] });
  const relationship = await adapter.retrieve({ scopes: ["relationship"] });

  const axioms = identityCore.find((r) => r.relativePath === "0_SOUL/axioms.md");
  const self = identityCore.find((r) => r.relativePath === "1_EGO/self.md");
  const owner = relationship.find((r) => r.relativePath === "4_RELATIONS/owner.md");

  if (!axioms) throw new Error("identity_core scope did not resolve 0_SOUL/axioms.md — check substrate.map.yaml");
  if (!self) throw new Error("identity_core scope did not resolve 1_EGO/self.md — check substrate.map.yaml");
  if (!owner) throw new Error("relationship scope did not resolve 4_RELATIONS/owner.md — check substrate.map.yaml");

  return { axioms: axioms.content, self: self.content, owner: owner.content };
}

interface CurrentStateFile { relativePath: string; content: string; }

/**
 * The always-changing layer. current_state's map entry declares
 * evidence_required: false, so a missing state/ directory or CURRENT.md
 * resolves to nothing and the immediate layer renders empty instead of
 * failing the compile (fail-closed applies to the curated core only).
 */
async function resolveCurrentState(substrateRoot: string): Promise<CurrentStateFile[]> {
  const adapter = adapterFor(substrateRoot, await Bun.file(joinPath(substrateRoot, "substrate.map.yaml")).text());
  const results = await adapter.retrieve({ scopes: ["current_state"] });
  return results
    .filter((r) => r.status === "ok" && r.content.trim().length > 0)
    .map((r) => ({ relativePath: r.relativePath, content: r.content }))
    .sort((a, b) => a.relativePath.localeCompare(b.relativePath));
}

/** Renders the immediate layer; null when no current_state sources resolved (block omitted from CORE_IDENTITY). */
function renderImmediate(files: CurrentStateFile[]): string | null {
  if (files.length === 0) return null;
  const sections = files.map((file) => `## From ${file.relativePath}\n\n${file.content.trim()}`);
  const body = [IMMEDIATE_HEADER, ...sections].join(SEP);
  return `${body.trim()}\n`;
}

function renderCoreIdentity(sources: { axioms: string; self: string; owner: string }, immediate: string | null): string {
  const header =
    "# Core Identity — Compiled\n\n" +
    "This file is generated by bruno's core-identity compiler from\n" +
    "axioms.md, self.md, and owner.md (resolved via the real\n" +
    "substrate.map.yaml — identity_core + relationship scopes), plus the\n" +
    "current_state immediate layer when present. Do not hand-edit; edit\n" +
    "the sources and let the compiler resynthesize.";
  const blocks = [
    header,
    `## From axioms.md (full)\n\n${sources.axioms.trim()}`,
    `## From self.md (distilled)\n\n${sources.self.trim()}`,
    `## From owner.md (distilled, private section full)\n\n${sources.owner.trim()}`,
    immediate,
    RECALL_SECTION.trim(),
  ].filter((block): block is string => block !== null);
  return blocks.join(SEP) + "\n";
}

const compileLock = new AsyncLock();

export async function compileBrunoCoreIdentity(paths: BrunoCoreIdentityPaths): Promise<BrunoCoreIdentityManifest> {
  return compileLock.acquire(async () => {
    const identityRuntimeRoot = paths.identityRuntimeRoot ?? defaultIdentityRuntimeRoot();
    const curated = await resolveCuratedSources(paths.substrateRoot);
    const currentStateFiles = await resolveCurrentState(paths.substrateRoot);

    const sourceHashes = {
      axioms: sha256Hex(curated.axioms),
      self: sha256Hex(curated.self),
      owner: sha256Hex(curated.owner),
      currentState: sha256Hex(currentStateFiles.map((f) => `${f.relativePath}\n${f.content}`).join("\n\n")),
    };

    const existing = await readManifest(identityRuntimeRoot);
    if (
      existing &&
      existing.compilerVersion === BRUNO_COMPILER_VERSION &&
      existing.sourceHashes.axioms === sourceHashes.axioms &&
      existing.sourceHashes.self === sourceHashes.self &&
      existing.sourceHashes.owner === sourceHashes.owner &&
      existing.sourceHashes.currentState === sourceHashes.currentState &&
      (await outputsIntact(identityRuntimeRoot, existing))
    ) {
      return existing;
    }

    const distiller = paths.distiller ?? new HeadingLeadParagraphDistiller();
    const distilled = {
      axioms: curated.axioms,
      self: await distiller.distill(curated.self),
      owner: await distiller.distill(curated.owner),
    };

    const immediate = renderImmediate(currentStateFiles);
    const core = renderCoreIdentity(distilled, immediate);

    const outDir = dirname(outputPath(identityRuntimeRoot));
    await mkdir(outDir, { recursive: true });
    await writeFileAtomic(immediateOutputPath(identityRuntimeRoot), immediate ?? EMPTY_IMMEDIATE);
    await writeFileAtomic(outputPath(identityRuntimeRoot), core);

    const manifest: BrunoCoreIdentityManifest = {
      sourceHashes,
      immediateHash: sha256Hex(immediate ?? EMPTY_IMMEDIATE),
      coreHash: sha256Hex(core),
      builtAt: new Date().toISOString(),
      compilerVersion: BRUNO_COMPILER_VERSION,
    };
    await writeFileAtomic(manifestPath(identityRuntimeRoot), JSON.stringify(manifest, null, 2));

    return manifest;
  });
}

/**
 * The "corrupted output" guard (eli SC-024/025 equivalent): a manifest
 * whose source hashes match but whose written files no longer hash to the
 * recorded values is treated as stale and recompiled, never served.
 */
async function outputsIntact(identityRuntimeRoot: string, manifest: BrunoCoreIdentityManifest): Promise<boolean> {
  const coreFile = Bun.file(outputPath(identityRuntimeRoot));
  const immediateFile = Bun.file(immediateOutputPath(identityRuntimeRoot));
  if (!(await coreFile.exists()) || !(await immediateFile.exists())) return false;
  const [core, immediate] = await Promise.all([coreFile.text(), immediateFile.text()]);
  return sha256Hex(core) === manifest.coreHash && sha256Hex(immediate) === manifest.immediateHash;
}

/** The compile output is a full RuntimeProjection — no cast needed at the service boundary. */
export type BrunoCoreIdentityRuntimeProjection = RuntimeProjection;

/**
 * ANIMA's compileProjection for bruno — mirrors eli's
 * readCoreIdentityProjection field-for-field (prompt = compiled file,
 * promptStaticHash = coreHash, substrateViewVersion = immediateHash,
 * DEFAULT_WRITE_SCOPES, everything else empty/unimplemented).
 */
export async function readBrunoCoreIdentityProjection(
  paths: BrunoCoreIdentityPaths,
): Promise<BrunoCoreIdentityRuntimeProjection> {
  // Idempotent: short-circuits when fresh, recompiles when stale or corrupted.
  const manifest = await compileBrunoCoreIdentity(paths);
  const identityRuntimeRoot = paths.identityRuntimeRoot ?? defaultIdentityRuntimeRoot();
  const core = await Bun.file(outputPath(identityRuntimeRoot)).text();
  const sources = await resolveCuratedSources(paths.substrateRoot);

  return {
    prompt: core,
    promptStaticHash: manifest.coreHash,
    kernelVersion: sha256Hex(`${sources.axioms.trim()}${SEP}${sources.self.trim()}`),
    cartridgeVersions: {},
    substrateViewVersion: manifest.immediateHash,
    readScopes: [],
    writeScopes: [...DEFAULT_WRITE_SCOPES],
    proposalScopes: [],
    declaredSubstrateScopes: [],
    scopeDeclarationStatus: "unimplemented",
  };
}
